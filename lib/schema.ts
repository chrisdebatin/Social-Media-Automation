export const templateIds = ['cover', 'photo', 'text', 'statement', 'quote', 'team', 'list', 'cta'] as const;
export type TemplateId = (typeof templateIds)[number];

export type TextSlot = 'headline' | 'subline' | 'body' | 'accent' | 'quote' | 'author' | 'button';

export interface SlotSpec {
  key: TextSlot;
  label: string;
  max: number;
  required: boolean;
  multiline?: boolean;
}

export interface TemplateSpec {
  id: TemplateId;
  label: string;
  description: string;
  slots: SlotSpec[];
  bullets?: { min: number; max: number; maxChars: number };
  /** 'photo' = normal photo, 'cutout' = transparent PNG person, 'none' = no photo slot */
  photo: 'photo' | 'cutout' | 'none';
  headlineStyles: HeadlineStyle[];
  defaultHeadlineStyle: HeadlineStyle;
}

const S = (key: TextSlot, label: string, max: number, required = true, multiline = false): SlotSpec => ({
  key, label, max, required, multiline,
});

