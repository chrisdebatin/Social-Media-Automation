/* ------------------------------------------------------------------ Slides */

export const photoRefSchema = z.object({
  /** "asset:people/x.png" | "https://…" | "data:image/…" */
  src: z.string().min(1),
  /** generated by AI → Instagram AI label */
  ai: z.boolean().optional(),
  note: z.string().optional(),
});
export type PhotoRef = z.infer<typeof photoRefSchema>;

export const slideSchema = z.object({
  id: z.string().min(1),
  template: z.enum(templateIds),
  headline: z.string().optional(),
  subline: z.string().optional(),
  body: z.string().optional(),
  accent: z.string().optional(),
  quote: z.string().optional(),
  author: z.string().optional(),
  button: z.string().optional(),
  bullets: z.array(z.string()).optional(),
  headlineStyle: z.enum(headlineStyles).optional(),
  photo: photoRefSchema.nullable().optional(),
  /** English prompt for a missing photo (AI images) */
  imagePrompt: z.string().optional(),
});
export type Slide = z.infer<typeof slideSchema>;

export const carouselSchema = z.object({
  slides: z.array(slideSchema).min(1).max(10),
  caption: z.string(),
  hashtags: z.array(z.string()),
});
export type Carousel = z.infer<typeof carouselSchema>;

export const draftSchema = carouselSchema.extend({
  id: z.string(),
  title: z.string(),
  updatedAt: z.string(),
  briefing: z.string().optional(),
  audience: z.string().optional(),
  location: z.string().optional(),
});
export type Draft = z.infer<typeof draftSchema>;

export const CAPTION_MAX = 2200;
export const HASHTAG_MAX = 30;

/** Unicode-aware character count (what the UI counter shows). */
export function charCount(s: string | undefined): number {
  return s ? [...s].length : 0;
}

export function newId(): string {
  return Math.random().toString(36).slice(2, 10);
}

export function emptySlide(template: TemplateId, id = newId()): Slide {
  const spec = templateCatalog[template];
  const slide: Slide = { id, template, headlineStyle: spec.defaultHeadlineStyle };
  for (const s of spec.slots) slide[s.key] = '';
  if (spec.bullets) slide.bullets = ['', '', ''];
  if (spec.photo !== 'none') slide.photo = null;
  return slide;
}

export function fullCaption(c: Pick<Carousel, 'caption' | 'hashtags'>): string {
  const tags = c.hashtags.map((h) => (h.startsWith('#') ? h : `#${h}`)).join(' ');
  return tags ? `${c.caption.trim()}\n\n${tags}` : c.caption.trim();
}

/** Slide needs a photo that is still missing (blocks publishing). */
export function missingPhoto(s: Slide): boolean {
  return templateCatalog[s.template].photo !== 'none' && !s.photo?.src;
}

